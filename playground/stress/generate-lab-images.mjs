import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

// Resolve the existing sharp copy through Nuxt Image's IPX dependency.
const require = createRequire(import.meta.url)
const imageRequire = createRequire(require.resolve('@nuxt/image'))
const ipxRequire = createRequire(imageRequire.resolve('ipx'))
const sharp = ipxRequire('sharp')
const output = fileURLToPath(new URL('../public/lab/', import.meta.url))
await mkdir(output, { recursive: true })
const digits = [
  '111101101101111',
  '010110010010111',
  '111001111100111',
  '111001111001111',
  '101101111001001',
  '111100111001111',
  '111100111101111',
  '111001001001001',
  '111101111101111',
  '111101111001111',
]
function svg(width, height, index, transparent = false) {
  const color = `#${((index * 2654435761) >>> 0).toString(16).padStart(8, '0').slice(0, 6)}`
  const label = String(index)
  const unit = Math.max(1, Math.floor(Math.min(width / (label.length * 4 + 2), height / 7)))
  let blocks = ''
  for (const [d, digit] of label.split('').entries()) {
    for (const [p, bit] of digits[Number(digit)].split('').entries()) {
      if (bit === '1')
        blocks += `<rect x="${unit * (1 + d * 4 + (p % 3))}" y="${unit * (1 + Math.floor(p / 3))}" width="${unit}" height="${unit}"/>`
    }
  }
  return Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">${transparent ? '' : `<rect width="100%" height="100%" fill="${color}"/>`}<g fill="${transparent ? color : '#ffffff'}">${blocks}</g></svg>`,
  )
}
const manifest = []
async function emit(name, width, height, index, format = 'jpeg') {
  const input = svg(width, height, index, format === 'png')
  const path = `${output}/${name}`
  if (format === 'svg') await writeFile(path, input)
  else if (format === 'gif') {
    const frames = await Promise.all(
      [index, index + 1].map((i) =>
        sharp(svg(width, height, i))
          .ensureAlpha()
          .raw()
          .toBuffer(),
      ),
    )
    await sharp(Buffer.concat(frames), {
      raw: { width, height: height * 2, channels: 4, pageHeight: height },
    })
      .gif({ loop: 0, delay: [250, 250] })
      .toFile(path)
  } else
    await sharp(input)
      .toFormat(format, format === 'jpeg' ? { quality: 75 } : {})
      .toFile(path)
  const metadata = await sharp(path, { animated: true }).metadata()
  manifest.push({
    id: name,
    src: `/lab/${encodeURIComponent(name)}`,
    width: metadata.width,
    height: metadata.pageHeight ?? metadata.height,
    set: index < 60 ? 'normal' : 'special',
  })
}
const started = performance.now()
for (let i = 0; i < 34; i++) {
  await emit(
    `normal-${String(i).padStart(2, '0')}.jpg`,
    800 + ((i * 613) % 3201),
    800 + ((i * 997) % 3201),
    i,
  )
}
for (const [i, [name, width, height, format]] of [
  ['huge.jpg', 8000, 6000, 'jpeg'],
  ['panorama.jpg', 4000, 80, 'jpeg'],
  ['tall.jpg', 80, 4000, 'jpeg'],
  ['transparent.png', 800, 600, 'png'],
  ['vector.svg', 800, 600, 'svg'],
  ['animated.gif', 320, 240, 'gif'],
].entries())
  await emit(name, width, height, 60 + i, format)
const alts = Object.fromEntries(
  manifest.map((photo) => [
    photo.id.replace(/\.[^.]+$/, ''),
    `Synthetic ${photo.id.replace(/\.[^.]+$/, '')} ${photo.width}×${photo.height}`,
  ]),
)
await mkdir(new URL('../lab/', import.meta.url), { recursive: true })
await writeFile(
  new URL('../lab/photos.ts', import.meta.url),
  `// Generated by playground/stress/generate-lab-images.mjs.\nexport const labAlt = ${JSON.stringify(alts, null, 2)}\n`,
)
process.stdout.write(
  `Generated ${manifest.length} images in ${((performance.now() - started) / 1000).toFixed(2)}s\n`,
)
