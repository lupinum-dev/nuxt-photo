import { execFileSync } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '../..')
const check = process.argv.includes('--check')

const outputs = {
  'gallery-basics.md': [
    'docs/content/docs/1.start/1.introduction.md',
    'docs/content/docs/1.start/2.get-started.md',
    'docs/content/docs/3.concepts/1.photo-data-and-dimensions.md',
  ],
  'customization.md': [
    'docs/content/docs/3.concepts/5.image-delivery.md',
    'docs/content/docs/3.concepts/4.ssr-and-layout-stability.md',
    'docs/content/docs/3.concepts/7.customization-levels.md',
    'docs/content/docs/2.guides/8.customize-the-built-in-lightbox.md',
    'docs/content/docs/2.guides/10.integrate-a-custom-image-service.md',
  ],
  'troubleshooting.md': [
    'docs/content/docs/5.help/1.troubleshooting.md',
    'docs/content/docs/5.help/2.known-constraints.md',
  ],
}

const site = 'https://nuxt-photo.lupinum.com'

function componentName(name) {
  return name
    .trim()
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')
}

// Match the website's agent Markdown: examples become their source files and
// install blocks become commands, because a skill reader cannot run the page.
async function exampleMarkdown(attributes) {
  const name = attributes.match(/name="([^"]+)"/)?.[1]
  const also = attributes.match(/also="([^"]+)"/)?.[1]
  const files = [name, ...(also?.split(',') ?? [])].filter(Boolean).map(componentName)
  const blocks = await Promise.all(
    files.map(async (file) => {
      const source = await readFile(resolve(root, 'docs/app/examples', `${file}.vue`), 'utf8')
      return `\`\`\`vue [app/components/${file}.vue]\n${source.trimEnd()}\n\`\`\``
    }),
  )
  return [
    `Complete example. Use it as \`<${files[0]} :photos="photos" />\` with your own \`PhotoItem[]\`.`,
    ...blocks,
  ].join('\n\n')
}

async function plainMarkdown(source, path) {
  const title = source.match(/^title:\s*['"]?(.+?)['"]?$/m)?.[1] ?? path
  let body = source
    .replace(/^---\n[\s\S]*?\n---\n/, '')
    .replace(/^::pm-install\{name="([^"]+)"\}\n::$/gm, '```bash [Terminal]\npnpm add $1\n```')
    .replace(/^::[a-z0-9-]+\n::\n?/gim, '')
    .replace(/:::read-more\{to="([^"]+)" title="([^"]+)"\}\n:::/g, '[$2]($1)')
    .replace(/\]\(\/docs\//g, `](${site}/docs/`)
    // The page title becomes a level-two heading, so page sections move down one level.
    .replace(/^(#{2,5}) /gm, '#$1 ')
    .trim()
  for (const match of body.matchAll(/^::example\{([^}]*)\}\n::$/gm)) {
    const example = await exampleMarkdown(match[1])
    // A function keeps `$&` and similar patterns in example code literal.
    body = body.replace(match[0], () => example)
  }
  return `## ${title}\n\n${body}\n\n_Source: ${site}${routeFor(path)}_\n`
}

function routeFor(path) {
  return (
    '/docs/' +
    path
      .replace('docs/content/docs/', '')
      .replace(/\.md$/, '')
      .split('/')
      .map((segment) => segment.replace(/^\d+\./, ''))
      .join('/')
  )
}

async function formatMarkdown(source, filename) {
  const temporaryDirectory = await mkdtemp(join(tmpdir(), 'nuxt-photo-doc-reference-'))
  const temporaryFile = join(temporaryDirectory, filename)

  try {
    await writeFile(temporaryFile, source)
    execFileSync('vp', ['fmt', temporaryFile, '--write'], {
      cwd: root,
      stdio: 'inherit',
    })
    return await readFile(temporaryFile, 'utf8')
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true })
  }
}

let stale = false

for (const [filename, sources] of Object.entries(outputs)) {
  const sections = []
  for (const sourcePath of sources) {
    const source = await readFile(resolve(root, sourcePath), 'utf8')
    sections.push(await plainMarkdown(source, sourcePath))
  }

  const generated = await formatMarkdown(
    [
      '<!-- Generated by vp run docs:agent. Do not edit directly. -->',
      '',
      `# ${filename.replace('.md', '').replaceAll('-', ' ')}`,
      '',
      ...sections,
    ].join('\n'),
    filename,
  )
  const target = resolve(root, 'skills/nuxt-photo/references', filename)

  if (check) {
    const current = await readFile(target, 'utf8').catch(() => '')
    if (current !== generated) {
      console.error(`${filename} is stale. Run vp run docs:agent.`)
      stale = true
    }
  } else {
    await writeFile(target, generated)
  }
}

if (stale) process.exitCode = 1
