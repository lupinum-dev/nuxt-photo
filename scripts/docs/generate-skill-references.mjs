import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { format, resolveConfig } from 'prettier'

const root = resolve(import.meta.dirname, '../..')
const check = process.argv.includes('--check')
const prettierConfig =
  (await resolveConfig(
    resolve(root, 'skills/nuxt-photo/references/gallery-basics.md'),
  )) ?? {}

const outputs = {
  'gallery-basics.md': [
    'docs/content/docs/2.getting-started/1.installation.md',
    'docs/content/docs/2.getting-started/2.first-gallery.md',
    'docs/content/docs/3.concepts/1.photo-model.md',
  ],
  'customization.md': [
    'docs/content/docs/3.concepts/5.image-pipeline.md',
    'docs/content/docs/3.concepts/4.ssr-and-layout-stability.md',
    'docs/content/docs/3.concepts/7.customization-layers.md',
    'docs/content/docs/4.guides/6.customize-the-lightbox.md',
    'docs/content/docs/4.guides/7.integrate-a-custom-image-service.md',
  ],
  'troubleshooting.md': [
    'docs/content/docs/6.help/1.troubleshooting.md',
    'docs/content/docs/6.help/2.sharp-edges.md',
  ],
}

function plainMarkdown(source, path) {
  const title = source.match(/^title:\s*['"]?(.+?)['"]?$/m)?.[1] ?? path
  const body = source
    .replace(/^---\n[\s\S]*?\n---\n/, '')
    .replace(/^::[a-z0-9-]+\n::\n?/gim, '')
    .replace(/:::read-more\{to="([^"]+)" title="([^"]+)"\}\n:::/g, '[$2]($1)')
    .trim()
  return `## ${title}\n\n${body}\n\n_Source: \`${path}\`_\n`
}

let stale = false

for (const [filename, sources] of Object.entries(outputs)) {
  const sections = []
  for (const sourcePath of sources) {
    const source = await readFile(resolve(root, sourcePath), 'utf8')
    sections.push(plainMarkdown(source, sourcePath))
  }

  const generated = await format(
    [
      '<!-- Generated by pnpm docs:agent. Do not edit directly. -->',
      '',
      `# ${filename.replace('.md', '').replaceAll('-', ' ')}`,
      '',
      ...sections,
    ].join('\n'),
    { ...prettierConfig, parser: 'markdown' },
  )
  const target = resolve(root, 'skills/nuxt-photo/references', filename)

  if (check) {
    const current = await readFile(target, 'utf8').catch(() => '')
    if (current !== generated) {
      console.error(`${filename} is stale. Run pnpm docs:agent.`)
      stale = true
    }
  } else {
    await writeFile(target, generated)
  }
}

if (stale) process.exitCode = 1
