import { execFileSync } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '../..')
const check = process.argv.includes('--check')

const outputs = {
  'gallery-basics.md': [
    'docs/content/docs/1.start/2.installation.md',
    'docs/content/docs/1.start/3.build-your-first-album.md',
    'docs/content/docs/3.concepts/1.photo-data-and-dimensions.md',
  ],
  'customization.md': [
    'docs/content/docs/3.concepts/5.image-delivery.md',
    'docs/content/docs/3.concepts/4.ssr-and-layout-stability.md',
    'docs/content/docs/3.concepts/7.customization-levels.md',
    'docs/content/docs/2.guides/8.customize-the-built-in-lightbox.md',
    'docs/content/docs/2.guides/10.integrate-a-custom-image-service.md',
  ],
  'troubleshooting.md': [
    'docs/content/docs/5.help/1.troubleshooting.md',
    'docs/content/docs/5.help/2.known-constraints.md',
  ],
}

function plainMarkdown(source, path) {
  const title = source.match(/^title:\s*['"]?(.+?)['"]?$/m)?.[1] ?? path
  const body = source
    .replace(/^---\n[\s\S]*?\n---\n/, '')
    .replace(/^::[a-z0-9-]+\n::\n?/gim, '')
    .replace(/:::read-more\{to="([^"]+)" title="([^"]+)"\}\n:::/g, '[$2]($1)')
    .trim()
  return `## ${title}\n\n${body}\n\n_Source: \`${path}\`_\n`
}

async function formatMarkdown(source, filename) {
  const temporaryDirectory = await mkdtemp(join(tmpdir(), 'nuxt-photo-doc-reference-'))
  const temporaryFile = join(temporaryDirectory, filename)

  try {
    await writeFile(temporaryFile, source)
    execFileSync('vp', ['fmt', temporaryFile, '--write'], {
      cwd: root,
      stdio: 'inherit',
    })
    return await readFile(temporaryFile, 'utf8')
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true })
  }
}

let stale = false

for (const [filename, sources] of Object.entries(outputs)) {
  const sections = []
  for (const sourcePath of sources) {
    const source = await readFile(resolve(root, sourcePath), 'utf8')
    sections.push(plainMarkdown(source, sourcePath))
  }

  const generated = await formatMarkdown(
    [
      '<!-- Generated by vp run docs:agent. Do not edit directly. -->',
      '',
      `# ${filename.replace('.md', '').replaceAll('-', ' ')}`,
      '',
      ...sections,
    ].join('\n'),
    filename,
  )
  const target = resolve(root, 'skills/nuxt-photo/references', filename)

  if (check) {
    const current = await readFile(target, 'utf8').catch(() => '')
    if (current !== generated) {
      console.error(`${filename} is stale. Run vp run docs:agent.`)
      stale = true
    }
  } else {
    await writeFile(target, generated)
  }
}

if (stale) process.exitCode = 1
